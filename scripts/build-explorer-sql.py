#!/usr/bin/env python3
"""Write the explorer's queries from the shared SQL in explorer/sql.

Every query starts with units.sql, so every pillar ranks the same facilities.
  themes/<t>.sql    -> config/themes/<t>/<t>-all.sql = units + body + score.sql (every facility)
  overview/<t>.sql  -> config/themes/<t>/<t>-all.sql = units + body (its own SELECT)
Each <t>.sql beside it is the same query filtered to the selected facility ({{ID}}), so a live
run returns exactly the precomputed rows. list.sql and the unit's cells go into config/app.json.
Run after editing anything in explorer/sql.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "explorer"
sql = root / "sql"
units, score = (sql / "units.sql").read_text(), (sql / "score.sql").read_text()
head = "-- Generated by scripts/build-explorer-sql.py from explorer/sql: edit those files, not this one.\n"


def write(t, full):
    out = root / "config" / "themes" / t
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{t}-all.sql").write_text(head + full)
    (out / f"{t}.sql").write_text(
        f"-- {t} for one facility ({{{{ID}}}}), generated by scripts/build-explorer-sql.py.\n"
        "-- Percentiles need every facility, so a live run costs as much as the all-facilities query;\n"
        "-- the app reads precomputed rows.\n"
        f"SELECT * EXCLUDE (id) FROM (\n{full}\n) WHERE id = {{{{ID}}}}\n")
    print(out / f"{t}-all.sql")


for body in sorted((sql / "themes").glob("*.sql")):
    write(body.stem, f"WITH\n{units}{body.read_text()}{score}")
for body in sorted((sql / "overview").glob("*.sql")):
    write(body.stem, f"WITH\n{units}{body.read_text()}")

# the list and the unit's cells, with the shared CTEs (the last one's trailing comma dropped)
ctes = "WITH\n" + units.rstrip().rstrip(",") + "\n"
app_file = root / "config" / "app.json"
app = json.loads(app_file.read_text())
jur = app["jurisdictions"][0]
jur["list"] = ctes + (sql / "list.sql").read_text()
jur["aoi"] = ctes + "SELECT DISTINCT h0, h8 FROM ring WHERE id = {{ID}}\n"
app_file.write_text(json.dumps(app, indent=4, ensure_ascii=False) + "\n")
print(app_file)
